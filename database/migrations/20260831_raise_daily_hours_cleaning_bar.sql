USE shift_mvp;

-- ============================================================================
-- 20260831：为保洁/吧台部门放宽单日工时上限（12h），解决 12 小时长班全职排不上
-- ----------------------------------------------------------------------------
-- 背景：S9 保洁班 / S6 吧台班均为 16:00-04:00（跨天 12 小时），而全职员工单日
--       工时上限 max_daily_work_hours 的 default 为 10h，导致：
--       - 全职保洁（周保洁/赵保洁）永远无法被分配 S9，整月几乎无班；
--       - 只能由兼职（单日不限）顶班。
-- 处理：仅对「保洁」「吧台」两个部门放宽单日上限至 12h，其余部门维持 10h。
--       引擎按部门字典读取（max_daily_work_hours 规则 JSON），default 为兜底。
-- 幂等：按 rule_key 精确更新，重复执行结果不变。
-- ============================================================================

UPDATE rule_configs
SET rule_value = '{"default":10,"兼职":0,"保洁":12,"吧台":12}',
    updated_at = CURRENT_TIMESTAMP
WHERE rule_key = 'max_daily_work_hours' AND store_id = 1;
