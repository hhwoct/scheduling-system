USE shift_mvp;

-- ============================================================================
-- 20260831：限制兼职员工每周工时上限，让全职优先有班
-- ----------------------------------------------------------------------------
-- 背景：兼职员工（E101~E110）跟随全局默认周工时 60h，与全职相同，
--       导致兼职在低技能岗位（保洁/咨客/传送/服务）大量顶班，
--       把全职（如保洁岗 E007 周保洁/E023 赵保洁）挤到整月几乎无班。
-- 处理：兼职改为个人自定义周工时上限 32h（与原 init 设计一致），
--       使算法优先排全职，兼职仅作补充。
-- 说明：排班引擎 EmployeeInput.MaxWeeklyHours 直接读取 employees.max_weekly_hours，
--       weekly_hours_follow_default=0 保证员工管理页也按个人值展示/使用。
-- 幂等：仅针对兼职（is_parttime=1）更新。
-- ============================================================================

UPDATE employees
SET weekly_hours_follow_default = 0,
    max_weekly_hours = 32
WHERE is_parttime = 1;
