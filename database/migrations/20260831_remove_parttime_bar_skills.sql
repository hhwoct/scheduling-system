USE shift_mvp;

-- ============================================================================
-- 20260831：清除兼职员工被错误授予的「内吧/外吧」技能
-- ----------------------------------------------------------------------------
-- 背景：兼职员工（E101~E110）被配置了内吧/外吧 3 分技能，而内吧/外吧并非
--       低技能岗位，系统规则为「兼职仅可分配低技能岗位（保洁/咨客/传送/服务）」。
--       结果：兼职大量占用内吧/外吧/保洁岗位需求，导致全职
--       尤内吧(E020)/许外吧(E021)/何吧台(E022)/赵保洁(E023) 整月无班被排休息。
-- 处理：将全部兼职（is_parttime=1）的内吧/外吧技能清为 0，让岗位回归由全职承担。
-- 幂等：仅清 skill_score>0 的行。
-- ============================================================================

UPDATE employee_skills es
JOIN employees e ON e.id = es.employee_id
JOIN workstations w ON w.id = es.workstation_id
SET es.skill_score = 0
WHERE e.is_parttime = 1
  AND w.code IN ('INNER_BAR', 'OUTER_BAR')
  AND es.skill_score > 0;
